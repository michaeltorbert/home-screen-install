// Static checks of the demos and path-safety checks of demo/serve.mjs.
// The server test listens on an ephemeral 127.0.0.1 port, never on 8796.

import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { request } from "node:http";
import { join } from "node:path";
import { after, before, describe, test } from "node:test";

import { ROOT, buildArtifacts } from "../scripts/build.mjs";
import { DEFAULT_PORT, createDemoServer } from "../demo/serve.mjs";

const read = (path) => readFileSync(join(ROOT, path), "utf8");
const DEMOS = [
  { id: "classic", name: "HSI Classic", script: "demo/classic/classic.js", dist: "dist/home-screen-install.js" },
  { id: "esm", name: "HSI ESM", script: "demo/esm/main.js", dist: "dist/home-screen-install.mjs" },
];

describe("demos", () => {
  const generated = new Set(buildArtifacts().keys());

  test("each demo is a separate Home Screen app with its own id, scope, name and icons", () => {
    const manifests = DEMOS.map(({ id }) => JSON.parse(read(`demo/${id}/manifest.webmanifest`)));
    for (const [index, { id, name }] of DEMOS.entries()) {
      const manifest = manifests[index];
      assert.equal(manifest.id, `/demo/${id}/`);
      assert.equal(manifest.start_url, `/demo/${id}/`);
      assert.equal(manifest.scope, `/demo/${id}/`);
      assert.equal(manifest.name, name);
      assert.equal(manifest.short_name, name);
      assert.equal(manifest.display, "standalone");
      for (const icon of manifest.icons) {
        assert.ok(generated.has(`demo/${id}/${icon.src}`), `${id}: ${icon.src} is generated by the build`);
      }
      const html = read(`demo/${id}/index.html`);
      assert.match(html, /<link rel="manifest" href="manifest\.webmanifest">/);
      assert.match(html, /<link rel="apple-touch-icon" href="icons\/icon-180\.png">/);
      assert.ok(generated.has(`demo/${id}/icons/icon-180.png`));
      assert.ok(html.includes(`<meta name="apple-mobile-web-app-title" content="${name}">`), `${id} title`);
      assert.ok(html.includes(`<title>${name}</title>`));
    }
    const distinct = (key) => new Set(manifests.map((manifest) => manifest[key])).size === manifests.length;
    for (const key of ["id", "name", "start_url", "scope", "theme_color"]) assert.ok(distinct(key), `${key} differs`);
  });

  test("demos consume the generated dist files only", () => {
    const classicHtml = read("demo/classic/index.html");
    assert.match(classicHtml, /<script src="\.\.\/\.\.\/dist\/home-screen-install\.js"><\/script>\s*<script src="classic\.js"><\/script>/);
    assert.match(read("demo/esm/index.html"), /<script type="module" src="main\.js"><\/script>/);
    assert.match(read("demo/esm/main.js"), /import\("\.\.\/\.\.\/dist\/home-screen-install\.mjs"\)/);
    for (const { id } of DEMOS) {
      const html = read(`demo/${id}/index.html`);
      for (const tag of html.match(/<script\b[^>]*>/g)) assert.match(tag, /\ssrc="/, `${id}: no inline scripts`);
      assert.doesNotMatch(html, /\/src\//);
    }
  });

  test("demo scripts use the shipped detector and set the status only after mount", () => {
    for (const { id, script } of DEMOS) {
      const code = read(script);
      for (const pattern of [/matchMedia/, /display-mode/, /\.standalone\b/, /userAgent/, /referrer/]) {
        assert.doesNotMatch(code, pattern, `${id}: no duplicated detector (${pattern})`);
      }
      const mountAt = code.indexOf(".mount(");
      const renderAt = code.indexOf("render(api.isStandaloneDisplay())");
      assert.ok(mountAt > 0 && renderAt > mountAt, `${id}: status is rendered after mount`);
      assert.ok(code.indexOf("api.watchDisplayMode(render)") > renderAt, `${id}: status follows watchDisplayMode`);
      assert.match(code, /showError\(/, `${id}: mount failures are shown`);
      assert.match(code, /window\.__homeScreenInstallDemo = /, `${id}: demo-only hook`);
    }
  });

  test("demo files make no external requests and contain no media or storage use", () => {
    const files = [
      "demo/index.html",
      "demo/demo.css",
      ...DEMOS.flatMap(({ id, script }) => [`demo/${id}/index.html`, `demo/${id}/manifest.webmanifest`, script]),
    ];
    const forbidden = [
      /https?:\/\//,
      /<(audio|video|iframe|object|embed)\b/i,
      /\bAudio\b/,
      /AudioContext/,
      /localStorage|sessionStorage|indexedDB|document\.cookie/,
      /\bfetch\s*\(/,
      /serviceWorker/,
      /@import|@font-face|url\(/,
    ];
    for (const path of files) {
      const text = read(path);
      for (const pattern of forbidden) assert.doesNotMatch(text, pattern, `${path}: ${pattern}`);
    }
  });
});

function get(port, path, method = "GET") {
  return new Promise((resolve, reject) => {
    const req = request({ host: "127.0.0.1", port, path, method }, (res) => {
      const chunks = [];
      res.on("data", (chunk) => chunks.push(chunk));
      res.on("end", () => resolve({ status: res.statusCode, headers: res.headers, body: Buffer.concat(chunks) }));
    });
    req.on("error", reject);
    req.end();
  });
}

describe("demo/serve.mjs", () => {
  const server = createDemoServer();
  let port;

  before(async () => {
    await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
    port = server.address().port;
    assert.notEqual(port, DEFAULT_PORT);
  });
  after(() => new Promise((resolve) => server.close(resolve)));

  test("defaults to the fixed native-demo port", () => {
    assert.equal(DEFAULT_PORT, 8796);
  });

  test("serves the demos and dist with explicit types", async () => {
    const cases = [
      ["/demo/", "text/html; charset=utf-8", "demo/index.html"],
      ["/demo/classic/", "text/html; charset=utf-8", "demo/classic/index.html"],
      ["/demo/esm/", "text/html; charset=utf-8", "demo/esm/index.html"],
      ["/demo/demo.css", "text/css; charset=utf-8", "demo/demo.css"],
      ["/demo/esm/main.js", "text/javascript; charset=utf-8", "demo/esm/main.js"],
      ["/demo/classic/manifest.webmanifest", "application/manifest+json", "demo/classic/manifest.webmanifest"],
      ["/demo/classic/icons/icon-180.png", "image/png", "demo/classic/icons/icon-180.png"],
      ["/demo/esm/icons/icon.svg", "image/svg+xml", "demo/esm/icons/icon.svg"],
      ["/dist/home-screen-install.js", "text/javascript; charset=utf-8", "dist/home-screen-install.js"],
      ["/dist/home-screen-install.mjs", "text/javascript; charset=utf-8", "dist/home-screen-install.mjs"],
    ];
    for (const [path, type, file] of cases) {
      const res = await get(port, path);
      assert.equal(res.status, 200, path);
      assert.equal(res.headers["content-type"], type, path);
      assert.equal(res.headers["x-content-type-options"], "nosniff", path);
      assert.ok(res.body.equals(readFileSync(join(ROOT, file))), path);
    }
    const head = await get(port, "/dist/home-screen-install.js", "HEAD");
    assert.equal(head.status, 200);
    assert.equal(head.body.length, 0);
  });

  test("redirects the root and directories without a trailing slash", async () => {
    const root = await get(port, "/");
    assert.equal(root.status, 302);
    assert.equal(root.headers.location, "/demo/");
    const dir = await get(port, "/demo/classic");
    assert.equal(dir.status, 301);
    assert.equal(dir.headers.location, "/demo/classic/");
  });

  test("refuses everything outside demo/ and dist/, traversal and unlisted types", async () => {
    const refused = [
      "/package.json",
      "/README.md",
      "/src/home-screen-install.js",
      "/scripts/build.mjs",
      "/test/core.test.mjs",
      "/demo/serve.mjs",
      "/dist/SHA256SUMS",
      "/../package.json",
      "/demo/../package.json",
      "/demo/%2e%2e/package.json",
      "/demo/..%2fpackage.json",
      "/demo/..%2F..%2Fpackage.json",
      "/demo/%2e%2e%2f%2e%2e%2fpackage.json",
      "/dist/..%2fsrc%2fhome-screen-install.js",
      "/demo/.hidden",
      "/demo//classic/",
      "/demo/classic/index.html/",
      "/demo/%00",
      "/demo/..%5cpackage.json",
      "/demo/%E0%A4%A",
    ];
    for (const path of refused) {
      const res = await get(port, path);
      assert.ok([400, 404].includes(res.status), `${path} -> ${res.status}`);
      assert.ok(!res.body.toString("utf8").includes('"name": "home-screen-install"'), path);
    }
    const post = await get(port, "/demo/", "POST");
    assert.equal(post.status, 405);
  });
});
